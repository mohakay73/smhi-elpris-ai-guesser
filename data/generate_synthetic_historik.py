"""
Generator for the SYNTHETIC seed history shipped with this starter repo.

READ THIS BEFORE YOU TRUST data/historik_elpris.csv OR data/historik_vader.csv
==============================================================================
The two CSV files in this folder are NOT real measurements. They were
generated by this script so that `model/train.py` runs end to end on a fresh
clone, before anyone has talked to an API.

They are shaped to match the real sources exactly -- same column names, same
separators, same timestamp conventions, same resolution change, same kinds of
holes -- so code written against them keeps working when you swap in real
data. But the numbers themselves are invented.

To replace them with the real thing, run:

    uv run python data/fetch_historik.py --from 2024-08-01 --to 2026-08-20

which downloads from elprisetjustnu.se and SMHI and overwrites both CSVs.
Do that before you draw any conclusion about Swedish electricity prices.

What is deliberately modelled here
----------------------------------
Everything in this list is also true of the real data. None of it is a bug.

1.  RESOLUTION CHANGE. Sweden moved from hourly to 15-minute electricity
    prices on 2025-10-01. Before that date each day has 24 price points;
    from that date it has 96. Any code that assumes "24 rows per day"
    silently breaks on data spanning the boundary.

2.  TWO TIMEZONE CONVENTIONS. Prices carry local Swedish time with an
    explicit UTC offset (+01:00 winter, +02:00 summer). SMHI observations
    are in UTC with no offset marker at all. Joining them naively is off by
    one or two hours depending on the season.

3.  DST DAYS. The last Sunday in March has 23 hours, the last Sunday in
    October has 25. Grouping by date and dividing by 24 is wrong twice a year.

4.  MISSING WEATHER HOURS. Real SMHI series drop individual hours when a
    sensor was down. Gaps here are mostly single hours, with a few multi-day
    outages.

5.  QUALITY CODES. SMHI marks each value G (checked and approved) or Y
    (suspect or aggregated). Y values are not wrong exactly, but they are
    not the same thing as G values either.

6.  NEGATIVE AND SPIKED PRICES. Sunny low-demand summer hours in SE3/SE4 can
    go below zero. Cold winter evenings can spike an order of magnitude above
    normal. Both are real, and both wreck a model that clips or drops them
    without thinking.

7.  A FEW DUPLICATE ROWS. Re-ingestion happens. The price files contain a
    small number of exact duplicate rows.

Author: course starter material, YH-02032.
"""

